_CATALOG_BY_ID: Dict[str, SpeciesCatalogItem] = {item.species_id: item for item in DEFAULT_SPECIES_CATALOG}


def list_species_catalog(
    category: Optional[PlantCategory] = None,
    query: Optional[str] = None,
) -> List[SpeciesCatalogItem]:
    """Return filtered botanical species catalog items."""
    items = DEFAULT_SPECIES_CATALOG
    if category is not None:
        items = [i for i in items if i.category == category]
    if query:
        q = query.strip().lower()
        items = [
            i
            for i in items
            if q in i.common_name.lower()
            or q in i.scientific_name.lower()
            or q in i.care_summary.lower()
        ]
    return items


def get_species_by_id(species_id: str) -> Optional[SpeciesCatalogItem]:
    """Return a single species catalog entry by ID."""
    return _CATALOG_BY_ID.get(species_id)
